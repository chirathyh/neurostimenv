def stream(seed: int, namespace: str) -> np.random.Generator:
    """Stable named SeedSequence streams without modifying global RNG state."""
    digest = hashlib.sha256(namespace.encode("utf-8")).digest()
    words = np.frombuffer(digest[:16], dtype="<u4").tolist()
    return np.random.default_rng(np.random.SeedSequence([int(seed), *words]))


def poisson_events(rate_hz: float, start_s: float, stop_s: float, rng: np.random.Generator) -> np.ndarray:
    """Homogeneous Poisson events generated by exponential inter-arrivals."""
    if not np.isfinite([rate_hz, start_s, stop_s]).all() or rate_hz < 0 or stop_s < start_s:
        raise ValueError("invalid Poisson rate or interval")
    if rate_hz == 0 or stop_s == start_s:
        return np.empty(0, dtype=np.float64)
    events = []
    current = float(start_s)
    while True:
        count = max(16, int((stop_s - current) * rate_hz * 1.25) + 1)
        block = current + np.cumsum(rng.exponential(1.0 / rate_hz, count))
        valid = block[block <= stop_s]
        events.extend(valid.tolist())
        if len(valid) < count:
            break
        current = float(block[-1])
    return np.asarray(events, dtype=np.float64)


def exponential_shot_noise(
    times_s: Sequence[float], events_s: Sequence[float], *, amplitude: float = 1.0,
    tau_s: float = 0.05, initial_time_s: float = 0.0, initial_state: float = 0.0,
) -> np.ndarray:
    """Exact causal exponential-kernel convolution, with right-closed events.

    `initial_state` is the complete state at `initial_time_s`; supplied events
    must occur strictly after that time. No discretization of event times is
    used. An event at an observation time contributes its complete amplitude.
    """
    times, events = np.asarray(times_s, dtype=np.float64), np.asarray(events_s, dtype=np.float64)
    if times.ndim != 1 or events.ndim != 1 or not np.isfinite(times).all() or not np.isfinite(events).all():
        raise ValueError("times and events must be finite vectors")
    if tau_s <= 0 or not np.isfinite([tau_s, amplitude, initial_state, initial_time_s]).all():
        raise ValueError("invalid kernel parameters")
    if np.any(np.diff(times) < 0) or np.any(times < initial_time_s):
        raise ValueError("sample times must be sorted after initial_time_s")
    if np.any(np.diff(events) <= 0) or np.any(events <= initial_time_s):
        raise ValueError("events must strictly increase after initial_time_s")
    values_at_events = np.empty(len(events), dtype=np.float64)
    state, previous = initial_state, initial_time_s
    for i, event in enumerate(events):
        state = state * np.exp(-(event - previous) / tau_s) + amplitude
        values_at_events[i], previous = state, event
    indices = np.searchsorted(events, times, side="right") - 1
    out = initial_state * np.exp(-(times - initial_time_s) / tau_s)
    has_event = indices >= 0
    selected = indices[has_event]
    out[has_event] = values_at_events[selected] * np.exp(-(times[has_event] - events[selected]) / tau_s)
    return out


def poisson_conditional_variance(leads_s: object, *, amplitude: float, rate_hz: float, tau_s: float) -> np.ndarray:
    """a² λ τ/2 (1-exp(-2h/τ)), conditional on all events through cutoff."""
    h = np.asarray(leads_s, dtype=np.float64)
    if np.any(h < 0) or not np.isfinite(h).all() or rate_hz < 0 or tau_s <= 0:
        raise ValueError("invalid lead, rate, or kernel time constant")
    return amplitude ** 2 * rate_hz * tau_s / 2 * (-np.expm1(-2 * h / tau_s))


def poisson_conditional_mean(leads_s: object, state: float, *, amplitude: float, rate_hz: float, tau_s: float) -> np.ndarray:
    h = np.asarray(leads_s, dtype=np.float64)
    poisson_conditional_variance(h, amplitude=amplitude, rate_hz=rate_hz, tau_s=tau_s)
    decay = np.exp(-h / tau_s)
    return decay * state + amplitude * rate_hz * tau_s * (1 - decay)


def poisson_forks(
    leads_s: Sequence[float], *, seed: int = 0, n_states: int = 8, n_futures: int = 64,
    amplitude: float = 1.0, rate_hz: float = 25.0, tau_s: float = 0.05,
    burn_in_tau: float = 20.0,
) -> dict:
    """Independent pasts and future innovations, conditional on each shot state.

    A finite independent 20τ prehistory leaves relative stationary-mean bias
    exp(-20) and stationary-variance bias exp(-40); no zero-start artifact is
    silently presented as exact stationarity.
    """
    h = np.asarray(leads_s, dtype=np.float64)
    if h.ndim != 1 or not len(h) or np.any(np.diff(h) < 0) or n_states < 1 or n_futures < 2 or burn_in_tau < 10:
        raise ValueError("invalid fork dimensions or insufficient prehistory")
    analytic = poisson_conditional_variance(h, amplitude=amplitude, rate_hz=rate_hz, tau_s=tau_s)
    states, histories = [], []
    futures = np.empty((n_states, n_futures, len(h)), dtype=np.float64)
    conditional_means = np.empty((n_states, len(h)), dtype=np.float64)
    future_events = []
    for s in range(n_states):
        past = poisson_events(rate_hz, -burn_in_tau * tau_s, 0, stream(seed, f"poisson/history/{s}"))
        state = float(exponential_shot_noise([0], past, amplitude=amplitude, tau_s=tau_s,
                                             initial_time_s=-burn_in_tau * tau_s)[0])
        histories.append(past)
        states.append(state)
        conditional_means[s] = poisson_conditional_mean(h, state, amplitude=amplitude, rate_hz=rate_hz, tau_s=tau_s)
        state_events = []
        for f in range(n_futures):
            events = poisson_events(rate_hz, 0, float(h[-1]), stream(seed, f"poisson/future/{s}/{f}"))
            futures[s, f] = exponential_shot_noise(h, events, amplitude=amplitude, tau_s=tau_s, initial_state=state)
            state_events.append(events)
        future_events.append(state_events)
    return {"futures": futures, "states": np.asarray(states), "histories": histories,
            "future_events": future_events, "conditional_mean": conditional_means,
            "analytic_variance": analytic, "leads_s": h, "burn_in_tau": burn_in_tau,
            "stationary_mean_relative_truncation": float(np.exp(-burn_in_tau)),
            "stationary_variance_relative_truncation": float(np.exp(-2 * burn_in_tau))}


def oscillator_transition(dt_s: float, *, frequency_hz: float = 10, damping_per_s: float = 3,
                          diffusion_variance_per_s: float = 6) -> tuple[np.ndarray, np.ndarray]:
    """Exact isotropically driven damped 2D oscillator transition and Q.

    dX = [[-γ,-ω],[ω,-γ]] X dt + sqrt(q) dW, H=[1,0].
    The stationary covariance is q/(2γ) I.
    """
    if dt_s < 0 or damping_per_s <= 0 or diffusion_variance_per_s < 0 or not np.isfinite(
        [dt_s, frequency_hz, damping_per_s, diffusion_variance_per_s]
    ).all():
        raise ValueError("invalid oscillator parameters")
    theta, attenuation = 2 * np.pi * frequency_hz * dt_s, np.exp(-damping_per_s * dt_s)
    F = attenuation * np.array([[np.cos(theta), -np.sin(theta)], [np.sin(theta), np.cos(theta)]])
    Q = np.eye(2) * diffusion_variance_per_s / (2 * damping_per_s) * (-np.expm1(-2 * damping_per_s * dt_s))
    return F, Q


def oscillator_path(n_samples: int, dt_s: float, *, seed: int = 0, frequency_hz: float = 10,
                    damping_per_s: float = 3, diffusion_variance_per_s: float = 6,
                    initial_state: Sequence[float] | None = None) -> np.ndarray:
    """Exact grid samples including time zero, with independently drawn stationary initial state."""
    if n_samples < 1:
        raise ValueError("n_samples must be positive")
    F, Q = oscillator_transition(dt_s, frequency_hz=frequency_hz, damping_per_s=damping_per_s,
                                  diffusion_variance_per_s=diffusion_variance_per_s)
    if initial_state is None:
        initial = stream(seed, "oscillator/initial_state").normal(size=2) * np.sqrt(diffusion_variance_per_s / (2 * damping_per_s))
    else:
        initial = np.asarray(initial_state, dtype=np.float64)
        if initial.shape != (2,) or not np.isfinite(initial).all():
            raise ValueError("initial_state must be a finite 2D vector")
    if n_samples == 1:
        return initial[None].copy()
    innovations = stream(seed, "oscillator/innovations").normal(size=(n_samples - 1, 2)) * np.sqrt(Q[0, 0])
    coefficient = complex(F[0, 0], F[1, 0])
    z0 = complex(*initial)
    z, _ = lfilter([1], [1, -coefficient], innovations[:, 0] + 1j * innovations[:, 1], zi=[coefficient * z0])
    z = np.concatenate(([z0], z))
    return np.column_stack((z.real, z.imag))


def kalman_filter(observations: object, F: np.ndarray, Q: np.ndarray, *, noise_variance: float,
                  initial_mean: Sequence[float] = (0, 0), initial_covariance: np.ndarray | None = None,
                  H: Sequence[float] = (1, 0)) -> tuple[np.ndarray, np.ndarray]:
    """Exact causal filtering; prior is at the first observation time.

    `noise_variance=0` is the clean-history oracle, not a full-state oracle:
    only the first state coordinate is observed. Uses the Joseph covariance
    update for numerical stability, including the zero-noise case.
    """
    observations = np.asarray(observations, dtype=np.float64)
    F, Q, H = np.asarray(F, dtype=np.float64), np.asarray(Q, dtype=np.float64), np.asarray(H, dtype=np.float64)
    if observations.ndim != 1 or not np.isfinite(observations).all() or noise_variance < 0:
        raise ValueError("invalid observations or noise variance")
    mean = np.asarray(initial_mean, dtype=np.float64).copy()
    covariance = np.eye(2) if initial_covariance is None else np.asarray(initial_covariance, dtype=np.float64).copy()
    means, covariances = [], []
    for index, observation in enumerate(observations):
        if index:
            mean, covariance = F @ mean, F @ covariance @ F.T + Q
        innovation_variance = float(H @ covariance @ H + noise_variance)
        if innovation_variance > 0:
            K = covariance @ H / innovation_variance
            mean += K * (observation - H @ mean)
            residual = np.eye(len(mean)) - np.outer(K, H)
            covariance = residual @ covariance @ residual.T + noise_variance * np.outer(K, K)
            covariance = (covariance + covariance.T) / 2
        means.append(mean.copy())
        covariances.append(covariance.copy())
    return np.asarray(means), np.asarray(covariances)


def oscillator_forecast(mean: Sequence[float], covariance: np.ndarray, leads_s: Sequence[float], **parameters: float) -> tuple[np.ndarray, np.ndarray]:
    """Predict the same clean first-component target at each lead."""
    predicted_means, predicted_variances = [], []
    for lead in leads_s:
        F, Q = oscillator_transition(float(lead), **parameters)
        predicted_means.append(float((F @ mean)[0]))
        predicted_variances.append(float((F @ covariance @ F.T + Q)[0, 0]))
    return np.asarray(predicted_means), np.asarray(predicted_variances)


def oscillator_risk_control(*, seed: int = 0, n_trials: int = 1024, history_samples: int = 32,
                            dt_s: float = 0.01, lead_samples: int = 4, noise_variance: float = 1.0,
                            frequency_hz: float = 9, damping_per_s: float = 2,
                            diffusion_variance_per_s: float = 4) -> dict:
    """Compare state, clean-history, noisy-history risks on identical targets.

    The same latent history and future target are scored in all three arms;
    only the information set changes. Independent noise is added only to
    history observations, never to the common clean target.
    """
    if n_trials < 2 or history_samples < 1 or lead_samples < 1:
        raise ValueError("invalid risk-control sample counts")
    params = dict(frequency_hz=frequency_hz, damping_per_s=damping_per_s,
                  diffusion_variance_per_s=diffusion_variance_per_s)
    F, Q = oscillator_transition(dt_s, **params)
    prior = np.eye(2) * diffusion_variance_per_s / (2 * damping_per_s)
    predictions = {key: [] for key in ("state_oracle", "clean_history", "noisy_history")}
    variances = {key: [] for key in predictions}
    targets = []
    for trial in range(n_trials):
        path_seed = int(stream(seed, f"kalman/path/{trial}").integers(0, 2**63))
        path = oscillator_path(history_samples + lead_samples, dt_s, seed=path_seed, **params)
        history = path[:history_samples, 0]
        noisy = history + stream(seed, f"kalman/sensor_noise/{trial}").normal(size=history_samples) * np.sqrt(noise_variance)
        clean_m, clean_P = kalman_filter(history, F, Q, noise_variance=0, initial_covariance=prior)
        noisy_m, noisy_P = kalman_filter(noisy, F, Q, noise_variance=noise_variance, initial_covariance=prior)
        beliefs = {"state_oracle": (path[history_samples - 1], np.zeros((2, 2))),
                   "clean_history": (clean_m[-1], clean_P[-1]), "noisy_history": (noisy_m[-1], noisy_P[-1])}
        targets.append(float(path[-1, 0]))
        for key, (mean, covariance) in beliefs.items():
            pred, risk = oscillator_forecast(mean, covariance, [lead_samples * dt_s], **params)
            predictions[key].append(float(pred[0]))
            variances[key].append(float(risk[0]))
    targets = np.asarray(targets)
    metrics = {}
    for key in predictions:
        errors = (targets - predictions[key]) ** 2
        metrics[key] = {"empirical_mse": float(errors.mean()), "mse_mc_standard_error": float(errors.std(ddof=1) / np.sqrt(n_trials)),
                        "exact_risk": float(np.mean(variances[key])), "n_trials": n_trials}
    metrics["target"] = "identical clean first-component future sample in all information arms"
    metrics["lead_s"] = lead_samples * dt_s
    metrics["history_s"] = (history_samples - 1) * dt_s
    metrics["noise_variance"] = noise_variance
    return metrics


def variance_class_posterior(history: object, *, sigmas: Sequence[float] = (1.0, 2.0)) -> np.ndarray:
    """Exact equal-prior p(C=1|history) using unstandardized squared samples."""
    x = np.asarray(history, dtype=np.float64)
    if x.ndim < 1 or x.shape[-1] < 1 or len(sigmas) != 2 or min(sigmas) <= 0 or not np.isfinite(x).all():
        raise ValueError("invalid Gaussian variance-control history")
    s0, s1 = np.asarray(sigmas, dtype=np.float64) ** 2
    log_ratio = -x.shape[-1] * np.log(sigmas[1] / sigmas[0]) + 0.5 * (1 / s0 - 1 / s1) * np.sum(x * x, axis=-1)
    return expit(log_ratio)


def gaussian_nll(target: object, mean: object, variance: object) -> np.ndarray:
    target, mean, variance = np.broadcast_arrays(np.asarray(target), np.asarray(mean), np.asarray(variance))
    if np.any(variance <= 0) or not np.isfinite(variance).all():
        raise ValueError("Gaussian variance must be finite and positive")
    return 0.5 * (np.log(2 * np.pi * variance) + (target - mean) ** 2 / variance)


def variance_mismatch_control(*, seed: int = 0, n_trials: int = 4096, history_samples: int = 32,
                              future_samples: int = 64, sigmas: Sequence[float] = (1, 2)) -> dict:
    """MSE has mean zero in both classes; variance remains useful for tasks/NLL.

    Positive controls use the exact known model, not fitted performance on
    their own training set. The Gaussian forecast matches conditional mean
    and variance; the exact conditional law is a two-Gaussian mixture.
    """
    if n_trials < 2 or history_samples < 1 or future_samples < 1 or len(sigmas) != 2 or min(sigmas) <= 0:
        raise ValueError("invalid variance-control settings")
    classes = np.arange(n_trials) % 2
    stream(seed, "variance/class_order").shuffle(classes)
    scales = np.asarray(sigmas)[classes]
    history = stream(seed, "variance/history").normal(size=(n_trials, history_samples)) * scales[:, None]
    target = stream(seed, "variance/independent_future").normal(size=(n_trials, future_samples)) * scales[:, None]
    posterior = variance_class_posterior(history, sigmas=sigmas)
    predicted_class = posterior >= 0.5
    balanced_accuracy = float(np.mean([(predicted_class[classes == c] == c).mean() for c in (0, 1)]))
    variance = (1 - posterior) * sigmas[0] ** 2 + posterior * sigmas[1] ** 2
    unconditional_variance = float(np.mean(np.square(sigmas)))
    conditional_nll = gaussian_nll(target, 0, variance[:, None])
    constant_nll = gaussian_nll(target, 0, unconditional_variance)
    return {"n_trials": n_trials, "history_samples": history_samples, "future_samples": future_samples,
            "sigmas": list(sigmas), "variance_classifier_balanced_accuracy": balanced_accuracy,
            "constant_mean_mse": float(np.mean(target ** 2)),
            "class_aware_mean_mse": float(np.mean(target ** 2)),
            "exact_population_mean_mse": unconditional_variance,
            "constant_gaussian_nll": float(constant_nll.mean()),
            "posterior_variance_gaussian_nll": float(conditional_nll.mean()),
            "nll_gain": float((constant_nll - conditional_nll).mean()),
            "mse_predictor": "zero for both classes; equality is algebraic, not an encoder-collapse claim",
            "normalization": "none; no per-window or per-trial scaling", "target_units": "analytical arbitrary units"}


def generate_trial(config: Mapping, spec: Mapping) -> dict:
    """Dataset adapter; includes burn-in, sampled on (0, total_duration].

    Future forks deterministically replay the complete prefix and its causal
    state. Analytical controls have no independent afferent phase innovation.
    """
    simulation = config.get("simulation", {})
    options = config.get("analytical", {})
    dt_ms = float(simulation.get("native_dt_ms", 0.0625))
    burn_s = float(simulation.get("burn_in_s", 2.0))
    duration_s = float(simulation.get("duration_s", 12.0))
    if dt_ms <= 0 or burn_s < 0 or duration_s <= 0:
        raise ValueError("invalid analytical sampling configuration")
    exact_n = (burn_s + duration_s) * 1000 / dt_ms
    if not np.isclose(exact_n, round(exact_n), rtol=0, atol=1e-7):
        raise ValueError("total analytical duration must align to the native time grid")
    n = int(round(exact_n))
    dt_s = dt_ms / 1000
    times = np.arange(1, n + 1, dtype=np.float64) * dt_s
    seed = int(spec.get("trial_seed", spec.get("seed", 0)))
    kind = str(config.get("data", {}).get("analytical_kind", "oscillator"))
    regime = spec.get("regime", {})
    if isinstance(regime, str):
        regime = {"name": regime}
    cutoff_ms = spec.get("future_start_ms")
    future_seed = spec.get("future_seed")
    if cutoff_ms is None and future_seed is not None:
        raise ValueError("future_seed requires an explicit future_start_ms")
    if cutoff_ms is not None and config.get("forks", {}).get("vary") == "phase":
        raise ValueError("analytical controls have no independent latent phase source; phase-only fork is undefined")
    cutoff_index = None
    if cutoff_ms is not None:
        cutoff_ms = float(cutoff_ms)
        fractional = cutoff_ms / dt_ms
        if not 0 <= cutoff_ms < times[-1] * 1000 or not np.isclose(fractional, round(fractional), rtol=0, atol=1e-7):
            raise ValueError("fork cutoff must be inside the recording and align to the native grid")
        cutoff_index = int(round(fractional))
        if future_seed is None:
            future_seed = seed
    privileged = {}
    amplitude_v = float(options.get("amplitude_v", 1e-6))
    if amplitude_v <= 0:
        raise ValueError("analytical amplitude_v must be positive")
    external_history = np.empty(0, dtype=np.float64)
    checkpoint = np.empty(0, dtype=np.float64)
    if kind == "poisson":
        tau = float(options.get("tau_s", 0.05))
        rate = float(options.get("rate_hz", 25.0))
        past_start = -20 * tau
        past = poisson_events(rate, past_start, 0, stream(seed, "poisson/prehistory"))
        if cutoff_index is None:
            future = poisson_events(rate, 0, float(times[-1]), stream(seed, "poisson/recorded_events"))
        else:
            cutoff_s = cutoff_ms / 1000
            prefix = poisson_events(rate, 0, cutoff_s, stream(seed, "poisson/recorded_events"))
            continuation = poisson_events(rate, cutoff_s, float(times[-1]), stream(int(future_seed), "poisson/future_events"))
            future = np.concatenate((prefix, continuation))
            external_history = np.concatenate((past, prefix))
            checkpoint = exponential_shot_noise([cutoff_s], external_history, amplitude=amplitude_v, tau_s=tau, initial_time_s=past_start)
        events = np.concatenate((past, future))
        eeg = exponential_shot_noise(times, events, amplitude=amplitude_v, tau_s=tau, initial_time_s=past_start)
        privileged = {"external_events_ms": events * 1000}
        namespaces = ["poisson/prehistory", "poisson/recorded_events", "poisson/future_events"]
        parameters = {"tau_s": tau, "rate_hz": rate, "prehistory_tau": 20,
                      "stationary_mean_relative_truncation": float(np.exp(-20))}
    elif kind == "oscillator":
        frequency = float(regime.get("frequency_hz", options.get("frequency_hz", 10)))
        damping = float(options.get("damping_per_s", 3))
        arguments = dict(frequency_hz=frequency, damping_per_s=damping, diffusion_variance_per_s=2 * damping)
        if cutoff_index is None:
            path = oscillator_path(n + 1, dt_s, seed=seed, **arguments)
        else:
            prefix = oscillator_path(cutoff_index + 1, dt_s, seed=seed, **arguments)
            continuation = oscillator_path(n - cutoff_index + 1, dt_s, seed=int(future_seed), initial_state=prefix[-1], **arguments)
            path = np.concatenate((prefix, continuation[1:]))
            checkpoint = prefix[-1] * amplitude_v
            # Historical stochastic forcing is completely reflected by the
            # replayed full-state trajectory. No RNG state is an observation.
            external_history = prefix
        eeg = path[1:, 0] * amplitude_v
        privileged = {"analytical_state_v": path[1:] * amplitude_v}
        namespaces = ["oscillator/initial_state", "oscillator/innovations"]
        parameters = {"frequency_hz": frequency, "damping_per_s": damping,
                      "diffusion_variance_v2_per_s": 2 * damping * amplitude_v ** 2}
    elif kind == "variance":
        class_id = int(spec.get("class_id", regime.get("variance_class", 0 if regime.get("name") == "R0" else 1)))
        if class_id not in (0, 1):
            raise ValueError("variance_class must be zero or one")
        sigmas = options.get("sigmas", [1, 2])
        if len(sigmas) != 2 or min(sigmas) <= 0:
            raise ValueError("sigmas must contain two positive numbers")
        sigma_v = float(sigmas[class_id]) * amplitude_v
        if cutoff_index is None:
            eeg = stream(seed, "variance/recording").normal(size=n) * sigma_v
        else:
            prefix = stream(seed, "variance/recording").normal(size=cutoff_index) * sigma_v
            continuation = stream(int(future_seed), "variance/future").normal(size=n - cutoff_index) * sigma_v
            eeg = np.concatenate((prefix, continuation))
            checkpoint = np.asarray([sigma_v])
            external_history = prefix
        privileged = {"variance_class": np.asarray(class_id)}
        namespaces = ["variance/recording", "variance/future"]
        parameters = {"variance_class": class_id, "sigma_v": sigma_v}
    else:
        raise ValueError(f"unknown analytical_kind: {kind}")
    structure_payload = {"kind": kind, "parameters": parameters, "structure_seed": int(spec.get("structure_seed", 0))}
    metadata = {"backend": "analytical", "analytical_kind": kind, "parameters": parameters,
                "structure_hash": hashlib.sha256(json.dumps(structure_payload, sort_keys=True).encode()).hexdigest(),
                "dipole_available": False, "dipole_note": "zero placeholder: analytical process has no physical dipole",
                "applied_field_v_per_m": 0.0, "sample_convention": "(0,total_duration]",
                "burn_in_s": burn_s, "native_dt_ms": dt_ms, "rng_namespaces": namespaces,
                "phase_innovation_source": "not applicable to analytical controls",
                "scientific_status": "analytical_control; not a biophysical circuit"}
    if cutoff_index is not None:
        metadata["fork"] = {"cutoff_ms": cutoff_ms,
                            "physical_state_hash": hashlib.sha256(np.ascontiguousarray(checkpoint).tobytes()).hexdigest(),
                            "external_history_hash": hashlib.sha256(np.ascontiguousarray(external_history).tobytes()).hexdigest(),
                            "pending_recurrent_hash": "not_applicable_no_recurrent_events",
                            "pending_external_hash": "not_applicable_no_external_delays",
                            "prefix_spike_hash": "not_applicable_no_spikes"}
        privileged.update(cutoff_physical_state=checkpoint,
                          pending_recurrent_events=np.empty((0, 6)), pending_external_events=np.empty((0, 6)))
    return {"time_ms": times * 1000, "eeg_v": np.asarray(eeg, dtype=np.float64)[:, None],
            "dipole_na_um": np.zeros((n, 3), dtype=np.float64), "privileged": privileged, "metadata": metadata}


def _atomic_json(path: Path, payload: dict) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    descriptor, tmp = tempfile.mkstemp(prefix=path.name + ".", suffix=".tmp", dir=path.parent)
    try:
        with os.fdopen(descriptor, "w") as handle:
            json.dump(payload, handle, indent=2, sort_keys=True, allow_nan=False)
            handle.write("\n")
            handle.flush()
            os.fsync(handle.fileno())
        os.replace(tmp, path)
    finally:
        if os.path.exists(tmp):
            os.unlink(tmp)


