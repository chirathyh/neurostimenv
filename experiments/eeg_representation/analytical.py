def oscillator_block_forecast(mean: Sequence[float], covariance: np.ndarray, leads_s: Sequence[float],
                              **parameters: float) -> tuple[np.ndarray, np.ndarray]:
    """Exact joint clean-target covariance, retaining cross-time correlations."""
    leads = np.asarray(leads_s, dtype=np.float64)
    if leads.ndim != 1 or not len(leads) or np.any(np.diff(leads) < 0) or np.any(leads < 0):
        raise ValueError("leads must be a nonempty sorted nonnegative vector")
    means, _ = oscillator_forecast(mean, covariance, leads, **parameters)
    block = np.empty((len(leads), len(leads)), dtype=np.float64)
    for i, lead in enumerate(leads):
        F, Q = oscillator_transition(float(lead), **parameters)
        P = F @ covariance @ F.T + Q
        for j in range(i, len(leads)):
            propagator, _ = oscillator_transition(float(leads[j] - lead), **parameters)
            block[i, j] = block[j, i] = (P @ propagator.T)[0, 0]
    return means, block


def oscillator_forks(leads_s: Sequence[float], *, seed: int = 0, n_states: int = 8, n_futures: int = 64,
                     frequency_hz: float = 10, damping_per_s: float = 3,
                     diffusion_variance_per_s: float = 6) -> dict:
    """Exact independent state-oracle continuations at arbitrary sorted leads."""
    leads = np.asarray(leads_s, dtype=np.float64)
    parameters = dict(frequency_hz=frequency_hz, damping_per_s=damping_per_s,
                      diffusion_variance_per_s=diffusion_variance_per_s)
    if n_states < 1 or n_futures < 2:
        raise ValueError("at least one state and two futures are required")
    _, covariance = oscillator_block_forecast([0, 0], np.zeros((2, 2)), leads, **parameters)
    states = stream(seed, "oscillator/fork_states").normal(size=(n_states, 2)) * np.sqrt(diffusion_variance_per_s / (2 * damping_per_s))
    futures = np.empty((n_states, n_futures, len(leads)))
    means = np.empty((n_states, len(leads)))
    for state_index, initial in enumerate(states):
        means[state_index], _ = oscillator_forecast(initial, np.zeros((2, 2)), leads, **parameters)
        for future_index in range(n_futures):
            rng = stream(seed, f"oscillator/future/{state_index}/{future_index}")
            current, last = initial.copy(), 0.0
            for j, lead in enumerate(leads):
                F, Q = oscillator_transition(float(lead - last), **parameters)
                current = F @ current + rng.normal(size=2) * np.sqrt(Q[0, 0])
                futures[state_index, future_index, j] = current[0]
                last = float(lead)
    return {"futures": futures, "states": states, "conditional_mean": means,
            "analytic_covariance": covariance, "analytic_variance": np.diag(covariance), "leads_s": leads}
